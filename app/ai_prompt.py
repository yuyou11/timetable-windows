"""
「用 AI 生成数据」的提示词。

## 为什么把提示词做成程序生成，而不是写死一段文字

提示词里最关键的三个值是**学期名称、第 1 周周一日期、总周数** ——
它们决定了整张课表的时间对不对。如果让 AI 去猜，它大概率会编一个日期，
而错一天的后果是每一周的课都错位。

所以这里从 Store 里读出来填进去。用户复制到的提示词**天然带着正确的学期信息**，
不需要他自己填，也就没有填错的机会。

## 内容与手机版保持一致

两边给 AI 的提示词越接近，用户在两台设备上得到的体验就越一致。
但有一处**必须不同**：手机版要提醒「用记事本另存为时选所有文件」这类坑，
电脑版不需要 —— 电脑版本身就能导出文件，用户不一定要手抄 JSON。
"""

from __future__ import annotations


class AiPrompt:

    @staticmethod
    def for_courses(term_name: str, start_date: str, total_weeks: int) -> str:
        return f"""你是数据格式转换助手。请把我提供的课程信息转换成下面这个 JSON 格式。

# 输出格式

顶层结构（字段顺序照这个来）：

{{
  "format": "timetable",
  "version": 2,
  "term": {{
    "name": "{term_name}",
    "startDate": "{start_date}",
    "totalWeeks": {total_weeks}
  }},
  "courses": [
    {{
      "name": "大学英语",
      "dayOfWeek": 1,
      "nodes": [1, 2],
      "weeks": "2-4,6-17",
      "place": "教一-101"
    }}
  ]
}}

# term 段（已经帮你填好，原样保留即可）

- name：学期名称
- startDate：教学第 1 周的**周一**，格式必须是 YYYY-MM-DD
- totalWeeks：总周数，所有 weeks 字段的取值不能超过这个数

# courses 数组，每门课一个对象

- name        课程名，字符串
- dayOfWeek   星期几，1 到 7 的整数（**周一=1**，周日=7）
- nodes       数组 [起始节次, 结束节次]，两个整数，范围 1-10 且起始 ≤ 结束
              连堂课写成 [1, 2]，**不要**拆成两条记录
- weeks       上课周次，字符串，写法见下
- place       教室，字符串；没有就整个省略这个字段
- enabled     false 表示这门课停开，一般不用写

## weeks 周次写法

  "3"          第 3 周
  "2-4"        第 2 到 4 周
  "3-17/2"     单周：3、5、7、9、11、13、15、17
  "2-16/2"     双周：2、4、6、8、10、12、14、16
  "2-4,6-17"   分段（第 2-4 周，以及第 6-17 周）
  "*"          全学期每周都上
  "3,5,7"      零散列举

如果原始课表写的是「单周」「双周」，请转换成上面的步长写法。

# 节次时间对照（帮助你理解，不要写进 JSON）

第 1 节 08:30-09:15     第 2 节 09:20-10:05
第 3 节 10:25-11:10     第 4 节 11:15-12:00
第 5 节 14:00-14:45     第 6 节 14:50-15:35
第 7 节 15:55-16:40     第 8 节 16:45-17:30
第 9 节 19:00-19:45     第 10 节 19:50-20:35

「1-2 节」表示第 1 节和第 2 节连堂，nodes 写 [1, 2]。

# 输出要求（重要）

1. **只输出 JSON 本身**。不要写「好的，我来帮你转换」这类开场白，
   不要写解释，不要写总结，不要在末尾加任何说明文字。
2. 不要用 ```json 代码块包起来，直接输出裸的 JSON。
3. 必须是严格合法的 JSON：字符串用双引号，不能有注释，不能有尾随逗号。
4. 中文直接写中文，不要转义成 \\uXXXX 这种形式。
5. 第一行是 {{，最后一行是 }}。

# 我提供的材料

（在这里粘贴课表内容，或者直接把课表文件、课表截图拖进来）
"""

    @staticmethod
    def for_templates(term_name: str) -> str:
        return f"""你是数据格式转换助手。请把我描述的日常作息转换成下面这个 JSON 格式。

（这是给「{term_name}」用的）

# 输出格式

{{
  "format": "timetable",
  "version": 2,
  "courses": [],
  "templates": {{
    "A": [
      {{ "start": "00:00", "end": "06:55", "title": "睡觉", "kind": "SLEEP" }},
      {{ "start": "06:55", "end": "07:10", "title": "起床、洗漱" }},
      {{ "start": "07:10", "end": "07:35", "title": "早餐", "kind": "MEAL" }},
      {{ "start": "08:30", "end": "10:05", "title": "第 1-2 节", "kind": "CLASS", "nodes": [1, 2] }}
    ]
  }}
}}

注意 "courses": [] 是**故意留空**的，表示「只改作息，不动课表」。
程序支持这样导入，不要替我把课程补上。

# templates 段

键是日型名称，只能从下面六个里选：

  "A"           有早八的日子（当天第 1-2 节有课时自动用这一套）
  "B_NORMAL"    没有早八的工作日
  "B_TRAIN_A"   没有早八的周二（训练日·力量A）
  "B_TRAIN_B"   没有早八的周四（训练日·力量B）
  "SATURDAY"    周六
  "SUNDAY"      周日

**你只需要输出我改动过的那几种**，没提到的日型会自动沿用内置模板。

# 每一格（block）

  start    开始时刻，字符串 "HH:mm"
  end      结束时刻，字符串 "HH:mm"；一天最后一段可以写 "24:00"
  title    这一格做什么，字符串（必需）
  note     补充说明（可选）
  kind     时段性质（可选，默认 CHORE），取值见下
  nodes    标成「课表格子」（可选），写法 [起始节次, 结束节次]

## kind 的取值

  SLEEP    睡觉（灰蓝）      MEAL     吃饭（橙）
  CLASS    上课/自习课（蓝）  STUDY    自习（紫）
  TRAIN    运动（红）        FREE     自由时间（绿）
  CHORE    洗漱等杂事（青）   TRANSIT  路上（灰）

## nodes 是什么

带 nodes 的格子是**占位符**：当天有课时会被整格替换成课程名和教室，
没课时显示成「第 3-4 节 · 无课」。

如果你希望某个时段由课程自动填充，就给它加上 nodes。
例如上午第 1-2 节、3-4 节、5-6 节、7-8 节、9-10 节这五段，
通常都该是 nodes 占位格，因为它们本来就可能有课。

节次范围是 1-10。「1-2 节」→ nodes: [1, 2]

# 两条硬性规则

1. **同一套模板里，格子之间不能有时间重叠。**
   比如 00:00-08:00 的「睡觉」和 07:00-24:00 的「早起」是冲突的，
   要么改成 08:00 开始，要么把睡觉的结束时间改到 07:00。
2. 尽量让每套模板从 00:00 连续铺到 24:00，中间不要留空。
   留空不是错误，但程序会自动填成「空档 · 机动」，通常不是你想要的。

# 输出要求

1. **只输出 JSON 本身**，不要开场白、不要解释、不要结尾总结。
2. 不要用 ```json 代码块包起来，直接输出裸的 JSON。
3. 严格合法：双引号、无注释、无尾随逗号。
4. 中文直接写中文，不要转义。
5. 第一行是 {{，最后一行是 }}。

# 我提供的材料

（在这里描述你的作息，例如：
「我早上 6:55 起床，洗漱 15 分钟，7:10 吃早饭，7:35 到 8:15 早读，
8:30 到 10:05 是第 1-2 节课，10:05 到 10:25 是大课间……」
有现成的作息表文件也可以直接上传）
"""

    @staticmethod
    def for_fix(error_message: str, generated_json: str) -> str:
        return f"""你刚才生成的时间规划表 JSON 导入失败了，程序报的错是：

---
{error_message}
---

请修正后重新输出完整的 JSON。注意：

1. 只输出 JSON 本身，不要任何解释文字，不要 ```json 代码块标记
2. 严格合法：字符串用双引号，不能有注释，不能有尾随逗号
3. 检查 weeks 里的周次有没有超出 totalWeeks
4. 检查 dayOfWeek 是否在 1-7 之间（周一=1）
5. 检查 nodes 是否是两个整数且起始 ≤ 结束，值在 1-10 之间
6. 检查 startDate 是不是周一，格式 YYYY-MM-DD

你上次生成的 JSON（供参考）：

{generated_json}
"""
